#!/usr/bin/env bun

/**
 * Prepare step for Azure Pipelines PR builds (before Pass 1).
 *
 *   1. Parse the pipeline env; skip anything that is not an Azure Repos PR
 *      build, a draft, or an inactive PR.
 *   2. Create or reuse the sticky tracking thread.
 *   3. Pick the PR iteration this build was queued for, check out its
 *      source commit, and write the diff / existing comments / description
 *      artifacts.
 *   4. Resolve review depth into model + effort and write the Pass-1 prompt,
 *      a sourceable env shim, and the state file the later steps read.
 */

import { spawnSync } from "child_process";
import * as fs from "fs/promises";
import * as path from "path";
import {
  parseAzureDevopsContext,
  reviewSkipReason,
  shortRefName,
} from "../azure-devops/context";
import {
  setupAzureDevopsAuth,
  withoutAzureDevopsTokens,
} from "../azure-devops/token";
import { AzureDevopsClient } from "../azure-devops/api/client";
import { azureDevopsApiVersion } from "../azure-devops/api/config";
import {
  buildTrackingCommentBody,
  upsertTrackingThread,
} from "../azure-devops/operations/tracking-thread";
import {
  resolveDiffRange,
  selectIteration,
  writeAzureDevopsReviewArtifacts,
} from "../azure-devops/data/review-artifacts";
import {
  checkoutDetached,
  createGitRunner,
  type GitRunner,
} from "../azure-devops/git";
import {
  generateAzureDevopsCandidatesPrompt,
  type AzureDevopsReviewPromptContext,
} from "../azure-devops/prompts";
import {
  candidatesFilePath,
  promptFilePath,
  promptsDir,
  resolvedEnvShimPath,
  validatedFilePath,
  writeState,
  type AzureDevopsPrepareState,
} from "../azure-devops/paths";
import { resolveReviewConfig } from "../utils/review-depth";
import { applyModelPolicyFallback } from "../utils/model-policy";
import {
  buildReviewSessionTag,
  type ReviewPass,
} from "../utils/review-session-tag";
import { setupDroidSettings } from "../../base-action/src/setup-droid-settings";
import { downgradeUnsupportedTierAlias } from "./gitlab-prepare";

function shellEscape(value: string): string {
  return `'${value.replace(/'/g, `'\\''`)}'`;
}

async function writeResolvedEnvShim(
  env: NodeJS.ProcessEnv,
  values: Record<string, string | null>,
): Promise<void> {
  const filePath = resolvedEnvShimPath(env);
  await fs.mkdir(path.dirname(filePath), { recursive: true });
  const lines = [
    "# Generated by azure-devops-prepare; source this to expose resolved review presets.",
    ...Object.entries(values).map(
      ([k, v]) => `export ${k}=${shellEscape(v ?? "")}`,
    ),
  ];
  await fs.writeFile(filePath, lines.join("\n") + "\n");
}

/** `droid exec --list-tools` probe that never sees Azure DevOps credentials. */
function probeModel(model: string): string {
  const result = spawnSync(
    "droid",
    ["exec", "--model", model, "--list-tools"],
    {
      encoding: "utf8",
      timeout: 60_000,
      env: withoutAzureDevopsTokens(process.env),
    },
  );
  return `${result.stdout ?? ""}${result.stderr ?? ""}`;
}

export type PrepareDeps = {
  env?: NodeJS.ProcessEnv;
  fetch?: (url: string, init: RequestInit) => Promise<Response>;
  git?: GitRunner;
  /** Resolves review depth into a model; defaults to the Factory policy check. */
  resolveModel?: (cfg: {
    model?: string;
    reasoningEffort?: string;
  }) => Promise<{ model?: string; reasoningEffort?: string }>;
  setupSettings?: (settings: string | undefined) => Promise<void>;
};

async function defaultResolveModel(cfg: {
  model?: string;
  reasoningEffort?: string;
}) {
  const resolved = await applyModelPolicyFallback(
    { ...cfg, model: downgradeUnsupportedTierAlias(cfg.model, probeModel) },
    { flowLabel: "code review", modelInputName: "review_model" },
  );
  if (resolved.fallbackNote) console.warn(resolved.fallbackNote);
  return resolved;
}

export async function run(
  deps: PrepareDeps = {},
): Promise<AzureDevopsPrepareState> {
  const env = deps.env ?? process.env;
  const ctx = parseAzureDevopsContext(env);
  const repository = `${ctx.project.name}/${ctx.repository.name}`;

  let state: AzureDevopsPrepareState = {
    shouldRunReview: false,
    collectionUri: ctx.collectionUri,
    project: ctx.project.id ?? ctx.project.name,
    repositoryId: ctx.repository.id,
    repository,
    pullRequestId: ctx.pullRequest?.id ?? null,
    iterationId: null,
    trackingThreadId: null,
    trackingCommentId: null,
    buildUrl: ctx.build.url,
    jobUrl: ctx.build.jobUrl,
    promptPath: null,
    resolvedModel: null,
    resolvedReasoningEffort: null,
    diffPath: null,
    commentsPath: null,
    descriptionPath: null,
    candidatesPath: null,
    validatedPath: null,
    sourceBranch: shortRefName(ctx.pullRequest?.sourceBranch) || null,
    targetBranch: shortRefName(ctx.pullRequest?.targetBranch) || null,
    headSha: ctx.pullRequest?.sourceCommitId ?? null,
    includeSuggestions: ctx.inputs.includeSuggestions,
    securityReviewEnabled: ctx.inputs.automaticSecurityReview,
    triggeredBy: ctx.user.name,
  };

  const skip = async (reason: string) => {
    console.log(`Skipping Droid review: ${reason}`);
    state = { ...state, shouldRunReview: false, reason };
    await writeState(state, env);
    return state;
  };

  const skipReason = reviewSkipReason(ctx);
  if (skipReason) return skip(skipReason);
  const pullRequestId = ctx.pullRequest!.id;

  const auth = setupAzureDevopsAuth(env);
  console.log(
    `Authenticating to ${ctx.hosting === "services" ? "Azure DevOps Services" : "Azure DevOps Server"} ` +
      `with ${auth.kind === "pat" ? "AZURE_DEVOPS_PAT" : "System.AccessToken"}.`,
  );

  try {
    await (deps.setupSettings ?? setupDroidSettings)(
      ctx.inputs.settings || undefined,
    );
  } catch (error) {
    console.warn("Failed to set up droid settings; using defaults:", error);
  }

  const client = new AzureDevopsClient({
    collectionUri: ctx.collectionUri,
    project: state.project,
    repositoryId: ctx.repository.id,
    auth,
    apiVersion: azureDevopsApiVersion(env),
    fetch: deps.fetch,
  });

  const pr = await client.getPullRequest(pullRequestId);
  if (pr.isDraft) return skip("draft-pull-request");
  if (pr.status !== "active") return skip(`pull-request-${pr.status}`);

  const threads = await client.listThreads(pullRequestId);
  const tracking = await upsertTrackingThread({
    client,
    pullRequestId,
    threads,
    body: buildTrackingCommentBody({
      state: "running",
      pipelineUrl: ctx.build.url,
      jobUrl: ctx.build.jobUrl,
      triggerUsername: ctx.user.name,
      securityReviewRan: ctx.inputs.automaticSecurityReview,
    }),
  });
  console.log(
    `${tracking.created ? "Created" : "Reused"} tracking thread ${tracking.threadId}`,
  );

  // Written now so a failure further down still flips the tracking thread
  // to "failure" instead of leaving it stuck on "running".
  state = {
    ...state,
    shouldRunReview: true,
    trackingThreadId: tracking.threadId,
    trackingCommentId: tracking.commentId,
    sourceBranch: shortRefName(pr.sourceRefName),
    targetBranch: shortRefName(pr.targetRefName),
  };
  await writeState(state, env);

  const iterations = await client.listIterations(pullRequestId);
  const iteration = selectIteration(
    iterations,
    ctx.pullRequest!.sourceCommitId,
  );
  const git =
    deps.git ?? createGitRunner(ctx.build.sourcesDirectory ?? process.cwd());
  const range = resolveDiffRange(git, iteration);
  checkoutDetached(git, range.head);
  console.log(
    `Reviewing iteration ${iteration.id}: ${range.base.slice(0, 12)}..${range.head.slice(0, 12)}`,
  );

  const outDir = promptsDir(env);
  const artifacts = await writeAzureDevopsReviewArtifacts({
    git,
    pr,
    threads,
    range,
    outDir,
  });

  const reviewConfig = resolveReviewConfig({
    reviewModel: ctx.inputs.reviewModel,
    reasoningEffort: ctx.inputs.reasoningEffort,
    reviewDepth: ctx.inputs.reviewDepth,
  });
  const resolved = await (deps.resolveModel ?? defaultResolveModel)(
    reviewConfig,
  );
  console.log(
    `Resolved review config: depth=${ctx.inputs.reviewDepth} => ` +
      `model=${resolved.model ?? "(org default)"} effort=${resolved.reasoningEffort ?? "(none)"}`,
  );

  const sessionTag = (pass: ReviewPass) =>
    JSON.stringify(
      buildReviewSessionTag({
        pass,
        reviewType: "code",
        platform: "azure-devops",
        repo: repository,
        pr: pullRequestId,
        securityReview: ctx.inputs.automaticSecurityReview,
        runId: ctx.build.id,
        runAttempt: ctx.build.jobAttempt,
      }),
    );

  await writeResolvedEnvShim(env, {
    RESOLVED_MODEL: resolved.model ?? null,
    RESOLVED_REASONING_EFFORT: resolved.reasoningEffort ?? null,
    DROID_PR_ID: String(pullRequestId),
    DROID_TRACKING_THREAD_ID: String(tracking.threadId),
    DROID_SESSION_TAG_CANDIDATES: sessionTag("candidates"),
    DROID_SESSION_TAG_VALIDATOR: sessionTag("validator"),
  });

  const promptCtx: AzureDevopsReviewPromptContext = {
    repository,
    pullRequestId,
    sourceBranch: state.sourceBranch ?? "",
    targetBranch: state.targetBranch ?? "",
    headSha: range.head,
    diffPath: artifacts.diffPath,
    commentsPath: artifacts.commentsPath,
    descriptionPath: artifacts.descriptionPath,
    candidatesPath: candidatesFilePath(env),
    validatedPath: validatedFilePath(env),
    includeSuggestions: ctx.inputs.includeSuggestions,
    securityReviewEnabled: ctx.inputs.automaticSecurityReview,
  };

  const promptPath = promptFilePath(env);
  await fs.mkdir(path.dirname(promptPath), { recursive: true });
  await fs.writeFile(
    promptPath,
    generateAzureDevopsCandidatesPrompt(promptCtx),
  );

  state = {
    ...state,
    iterationId: iteration.id,
    promptPath,
    resolvedModel: resolved.model ?? null,
    resolvedReasoningEffort: resolved.reasoningEffort ?? null,
    diffPath: artifacts.diffPath,
    commentsPath: artifacts.commentsPath,
    descriptionPath: artifacts.descriptionPath,
    candidatesPath: promptCtx.candidatesPath,
    validatedPath: promptCtx.validatedPath,
    headSha: range.head,
  };
  await writeState(state, env);
  console.log(`Wrote Pass-1 prompt to ${promptPath}`);
  return state;
}

if (import.meta.main) {
  run().catch((error) => {
    console.error("azure-devops-prepare failed:", error);
    process.exit(1);
  });
}
