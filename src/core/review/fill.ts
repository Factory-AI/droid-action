import { findTopLevelCommentRange } from "./markers";

export const FILL_START = "<!-- droid-fill:start -->";
export const FILL_END = "<!-- droid-fill:end -->";

/** Only the marked region is bot-owned. Author text is preserved byte-for-byte. */
export function updateGeneratedDescription(
  existing: string,
  generated: string,
  head: string,
): string {
  if (generated.includes(FILL_START) || generated.includes(FILL_END)) {
    throw new Error(
      "Submit only the generated content, without Droid fill markers",
    );
  }
  const range = findTopLevelCommentRange(existing, FILL_START, FILL_END);
  const sha = /^[0-9a-f]{7,64}$/i.test(head) ? head.slice(0, 7) : "unknown";
  const block = `${FILL_START}\n${generated.trim()}\n\n<sub>Generated by Droid from ${sha} · edit freely</sub>\n${FILL_END}`;
  const prefix = range
    ? existing.slice(0, range.start)
    : `${existing}${existing ? "\n\n" : ""}`;
  const assembled = prefix + block + (range ? existing.slice(range.end) : "");
  const recovered = findTopLevelCommentRange(assembled, FILL_START, FILL_END);
  if (
    recovered?.start !== prefix.length ||
    recovered.end !== prefix.length + block.length
  ) {
    throw new Error(
      "Description markers would be hidden by Markdown; refusing to publish.",
    );
  }
  return assembled;
}
