import { describe, expect, it } from "bun:test";
import {
  cleanDescription,
  createGitHubPRServer,
  extractIssueReferences,
  handleUpdatePRDescription,
  mergeDescriptions,
} from "./github-pr-server";

type MockCall<TArgs extends unknown[]> = {
  args: TArgs;
};

function createMockOctokit(
  existingBody = "",
  pullData = { body: existingBody, head: { sha: "abc123456789" } },
) {
  const updateCalls: MockCall<[any]>[] = [];
  const getCalls: MockCall<[any]>[] = [];

  return {
    rest: {
      pulls: {
        update: async (params: any) => {
          updateCalls.push({ args: [params] });
          return { data: {} };
        },
        get: async (params: any) => {
          getCalls.push({ args: [params] });
          return { data: pullData };
        },
        listReviewComments: async () => ({ data: [] }),
        createReview: async () => ({ data: { id: 1 } }),
        deleteReviewComment: async () => ({}),
        getReviewComment: async () => ({ data: { node_id: "node" } }),
        createReplyForReviewComment: async () => ({ data: { id: 1 } }),
      },
      issues: {
        listComments: async () => ({ data: [] }),
        deleteComment: async () => ({}),
        getComment: async () => ({ data: { node_id: "node" } }),
        createComment: async () => ({ data: { id: 1 } }),
      },
    },
    __calls: {
      update: updateCalls,
      get: getCalls,
    },
  } as const;
}

describe("github-pr-server", () => {
  it("should remove @droid fill placeholder in cleanDescription", () => {
    const input = "## Summary\n@droid fill\nActual content";
    expect(cleanDescription(input)).toBe("## Summary\nActual content");
  });

  it("should extract issue references", () => {
    const refs = extractIssueReferences("Fixes #123 and closes #456");
    expect(refs).toEqual(["Fixes #123", "closes #456"]);
  });

  it("should merge descriptions preserving issue references", () => {
    const existing = "Existing body\nFixes #123";
    const generated = "## Summary\nNew content";
    const merged = mergeDescriptions(existing, generated);
    expect(merged).toContain("New content");
    expect(merged).toContain("Fixes #123");
  });

  it("should update PR description in replace mode", async () => {
    const octokit = createMockOctokit();

    const updated = await handleUpdatePRDescription({
      owner: "test-owner",
      repo: "test-repo",
      prNumber: 123,
      body: "## Description\n@droid fill\nActual content",
      mode: "replace",
      octokit,
    });

    expect(updated).toBe("## Description\nActual content");
    expect(octokit.__calls.get.length).toBe(0);
    expect(octokit.__calls.update[0]?.args[0].body).toBe(updated);
  });

  it("should merge with existing description in merge mode", async () => {
    const octokit = createMockOctokit("Existing content\nFixes #456");

    const updated = await handleUpdatePRDescription({
      owner: "test-owner",
      repo: "test-repo",
      prNumber: 123,
      body: "## New Section\nNew content",
      mode: "merge",
      octokit,
    });

    expect(octokit.__calls.get.length).toBe(1);
    expect(updated).toContain("New content");
    expect(updated).toContain("Fixes #456");
    expect(octokit.__calls.update[0]?.args[0].body).toBe(updated);
  });

  it("should create server with tool", () => {
    const octokit = createMockOctokit();
    const server = createGitHubPRServer({
      owner: "test-owner",
      repo: "test-repo",
      octokit,
    });

    expect(server).toBeDefined();
  });
  it("preserves author content and replaces only the generated description region", async () => {
    const author = "Manual notes\nFixes #123\n\n";
    const octokit = createMockOctokit(
      `${author}<!-- droid-fill:start -->\nold\n<!-- droid-fill:end -->\nManual footer`,
    );
    const updated = await handleUpdatePRDescription({
      owner: "org",
      repo: "repo",
      prNumber: 12,
      body: "## Summary\nNew changes",
      mode: "generated",
      octokit,
    });
    expect(updated.startsWith(author)).toBe(true);
    expect(updated.endsWith("\nManual footer")).toBe(true);
    expect(updated).toContain("Generated by Droid from abc1234 · edit freely");
    expect(updated).not.toContain("\nold\n");
  });
  it("renders the security-full PR index and verification checklist from approved validation only", async () => {
    const source = "a".repeat(40);
    const fixed = "b".repeat(40);
    const branch = "droid/security-report-fixture";
    const env = {
      DROID_EXEC_RUN_TYPE: "droid-security-scan",
      SECURITY_REPORT_SOURCE_REVISION: source,
      SECURITY_REPORT_BRANCH: branch,
      SECURITY_REPORT_BASE_BRANCH: "main",
      SECURITY_REPORT_AUTHOR: "factory-droid[bot]",
      SECURITY_REPORT_ACTOR: "human",
      SECURITY_REPORT_TRIGGER_NUMBER: "41",
    };
    const saved = new Map(
      Object.keys(env).map((key) => [key, process.env[key]]),
    );
    Object.assign(process.env, env);
    try {
      const ownedReport = {
        state: "open",
        merged: false,
        body: "Owned report placeholder",
        user: { login: "factory-droid[bot]", type: "Bot" },
        head: {
          sha: fixed,
          ref: branch,
          repo: { full_name: "org/repo" },
        },
        base: { ref: "main", repo: { full_name: "org/repo" } },
      };
      const octokit = createMockOctokit("", ownedReport);
      const updated = await handleUpdatePRDescription({
        owner: "org",
        repo: "repo",
        prNumber: 12,
        mode: "security-report",
        octokit,
        body: JSON.stringify({
          meta: { headSha: source },
          securityReport: {
            sourceRevision: source,
            outcomes: [
              {
                id: "f-sec",
                disposition: "patched",
                fixCommit: fixed,
                verification: "Cross-tenant regression passed after patch",
              },
            ],
          },
          results: [
            {
              status: "approved",
              comment: {
                id: "f-sec",
                title: "Tenant isolation fails",
                severity: "P1",
                security: true,
                path: "src/auth.ts",
                line: 8,
                body: "A tenant can read another tenant's data.",
                verification: "Run the cross-tenant regression test",
                outside_diff: true,
                commit_id: source,
              },
            },
            {
              status: "rejected",
              comment: { title: "Rejected allegation", path: "src/auth.ts" },
              reason: "Not reachable",
            },
          ],
        }),
      });
      expect(updated).toContain("### Findings index");
      expect(updated).toContain("#droid-security-1");
      expect(updated).toContain("**How to verify**");
      expect(updated).toContain("cross-tenant regression test");
      expect(updated).not.toContain("Rejected allegation");
      expect(updated).toContain(`/blob/${source}/src/auth.ts`);
      expect(updated).not.toContain(`/blob/${fixed}/src/auth.ts`);
      expect(updated).toContain(
        `**Reported patched** in \`${fixed.slice(0, 7)}\` (reported by the scan, not independently verified by this renderer).`,
      );
      expect(octokit.__calls.get.map((call) => call.args[0])).toEqual([
        { owner: "org", repo: "repo", pull_number: 12 },
        { owner: "org", repo: "repo", pull_number: 12 },
      ]);
      expect(octokit.__calls.update).toHaveLength(1);
      expect(octokit.__calls.update[0]?.args[0]).toEqual({
        owner: "org",
        repo: "repo",
        pull_number: 12,
        body: updated,
      });
    } finally {
      for (const [key, value] of saved) {
        if (value === undefined) delete process.env[key];
        else process.env[key] = value;
      }
    }
  });
});
