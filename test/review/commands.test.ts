import { describe, expect, test } from "bun:test";
import { parseDroidCommand } from "../../src/core/review/triggers/parse-command";
import {
  updateGeneratedDescription,
  FILL_START,
  FILL_END,
} from "../../src/core/review/fill";
import { checkContainsTrigger } from "../../src/github/validation/trigger";
import { extractCommandFromContext } from "../../src/github/utils/command-parser";
import { appTokenPermissionsFor } from "../../src/github/token-permissions";
import { createMockContext } from "../mockContext";

describe("review UX command grammar", () => {
  test.each([
    ["@droid", "default"],
    ["@droid!", "default"],
    ["@DROID: HELP!", "help"],
    ["@droid review", "review"],
    ["@droid review --full", "review"],
    ["@DROID: REVIEW --FULL.", "review"],
    ["@droid review the migration for locking issues", "review"],
    ["@droid security", "security"],
    ["@droid review security", "security"],
    ["@DROID REVIEW SECURITY --FULL", "security-full"],
    ["@droid security --full", "security-full"],
    ["@DROID, SECURITY --FULL!", "security-full"],
    ["@droid fix", "unknown"],
    ["@droid resolve.", "resolve"],
    ["@droid pause", "pause"],
    ["@droid resume", "resume"],
    ["@droid remember this", "unknown"],
    ["@droid reviewer", "unknown"],
  ])("%s routes to %s", (text, command) =>
    expect(String(parseDroidCommand(text)?.command)).toBe(command),
  );

  test("preserves focus independently of full override", () => {
    expect(
      parseDroidCommand("@droid review --full the migration"),
    ).toMatchObject({
      command: "review",
      fullReview: true,
      focus: "the migration",
    });
    expect(parseDroidCommand("@droid review security --full")).toMatchObject({
      command: "security-full",
    });
  });
  test.each([
    "```\n@droid fix\n```",
    "~~~text\n@droid review\n~~~",
    "`@droid review`",
    "````md\n```\n@droid fix\n```\n````",
    "user@droid.com",
    "@droid-bot review",
  ])("ignores code and lookalikes: %s", (text) =>
    expect(parseDroidCommand(text)).toBeNull(),
  );
  test("finds real command after fenced sample", () => {
    expect(
      parseDroidCommand("```md\n@droid fix\n```\n@droid help")?.command,
    ).toBe("help");
  });
  test("fenced trigger is ignored all the way through trigger and permission narrowing", () => {
    const context = createMockContext({
      eventName: "issue_comment",
      isPR: true,
      payload: { comment: { body: "```\n@droid fix\n```" } } as any,
    });
    expect(checkContainsTrigger(context)).toBe(false);
    expect(appTokenPermissionsFor(context).contents).toBe("read");
  });
  test("PR prose cannot authorize state changes; controls keep read-only contents access", () => {
    const context = createMockContext({
      eventName: "pull_request",
      isPR: true,
      payload: { pull_request: { body: "@droid pause" } } as any,
    });
    expect(extractCommandFromContext(context)?.command).toBe("unknown");
    expect(appTokenPermissionsFor(context).contents).toBe("read");
    const comment = createMockContext({
      eventName: "issue_comment",
      isPR: true,
      inputs: { ...context.inputs, automaticReview: true },
      payload: { comment: { body: "@droid pause" } } as any,
    });
    expect(appTokenPermissionsFor(comment).contents).toBe("read");
  });
  test("free text becomes a question only in a review comment", () => {
    const context = createMockContext({
      eventName: "pull_request_review_comment",
      isPR: true,
      payload: { comment: { body: "@droid why is this unsafe?" } } as any,
    });
    expect(extractCommandFromContext(context)).toMatchObject({
      command: "question",
      text: "why is this unsafe?",
    });
  });
});

describe("generated description ownership", () => {
  test("appends a marked block without changing author text", () => {
    const author = "Author's notes\nFixes #123\n\n";
    const result = updateGeneratedDescription(
      author,
      "## Summary\nChanges",
      "abc123456789",
    );
    expect(result.startsWith(author)).toBe(true);
    expect(result).toContain(FILL_START);
    expect(result).toContain("Generated by Droid from abc1234 · edit freely");
  });
  test("replaces only the old generated region and keeps text after it", () => {
    const prefix = "Manual notes\n\n",
      suffix = "\n\nAuthor checklist\n- [ ] Verify";
    const result = updateGeneratedDescription(
      `${prefix}${FILL_START}\nold\n${FILL_END}${suffix}`,
      "new",
      "abc1234567",
    );
    expect(result.startsWith(prefix)).toBe(true);
    expect(result.endsWith(suffix)).toBe(true);
    expect(result).not.toContain("\nold\n");
    expect(result.split(FILL_START)).toHaveLength(2);
  });
  test.each(["```md", "~~~md"])(
    "preserves an author-only %s marker example when appending",
    (fence) => {
      const author = `Author notes\r\n\r\n${fence}\r\n${FILL_START}\r\nAuthor example content\r\n${FILL_END}\r\n${fence.slice(0, 3)}\r\n\r\nAuthor checklist`;
      const result = updateGeneratedDescription(author, "new", "abc1234567");
      const block = updateGeneratedDescription("", "new", "abc1234567");
      expect(result).toBe(`${author}\n\n${block}`);
      expect(updateGeneratedDescription(result, "new", "abc1234567")).toBe(
        result,
      );
    },
  );
  test.each(["```md", "~~~md"])(
    "replaces only the real block after a %s example and stays idempotent",
    (fence) => {
      const prefix = `Manual notes\r\n\r\n${fence}\r\n${FILL_START}\r\nAuthor example content\r\n${FILL_END}\r\n${fence.slice(0, 3)}\r\n\r\n`;
      const suffix = `\r\n\r\nAuthor checklist\r\n- [ ] Verify\r\n\r\n${fence}\r\n${FILL_START}\r\nAuthor example after generated content\r\n${FILL_END}\r\n${fence.slice(0, 3)}`;
      const existing = `${prefix}${FILL_START}\r\nold generated content\r\n${FILL_END}${suffix}`;
      const result = updateGeneratedDescription(existing, "new", "abc1234567");
      const block = updateGeneratedDescription("", "new", "abc1234567");
      expect(result).toBe(`${prefix}${block}${suffix}`);
      expect(updateGeneratedDescription(result, "new", "abc1234567")).toBe(
        result,
      );
    },
  );
  test.each([
    FILL_START,
    FILL_END,
    `${FILL_END}\n${FILL_START}`,
    `${FILL_START}\n${FILL_START}\n${FILL_END}`,
  ])("refuses malformed existing markers", (existing) => {
    expect(() =>
      updateGeneratedDescription(existing, "new", "abc1234567"),
    ).toThrow("markers");
  });
});
